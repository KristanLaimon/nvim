local t = require("fox.lib.foxnvim.test")
local function feed(s)
	vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes(s, true, false, true), "xt", false)
end
t.describe("native pairs through real insert mappings and Blink", function()
	local old, buf
	t.beforeEach(function()
		old = vim.api.nvim_get_current_buf()
		buf = vim.api.nvim_create_buf(false, true)
		vim.api.nvim_set_current_buf(buf)
		vim.bo.filetype = "text"
		vim.bo.autoindent = true
		vim.bo.expandtab = true
		vim.bo.shiftwidth = 2
	end)
	t.afterEach(function()
		feed("<Esc>")
		vim.api.nvim_set_current_buf(old)
		vim.api.nvim_buf_delete(buf, { force = true })
	end)
	t.it("retires the external spec and keeps pair mappings after Blink loads", function()
		require("lazy").load({ plugins = { "blink.cmp" } })
		t.expect(require("lazy.core.config").plugins["nvim-autopairs"]).toBe(nil)
		for _, path in ipairs(vim.api.nvim_list_runtime_paths()) do
			t.expect(path:find("nvim-autopairs", 1, true)).toBe(nil)
		end
		feed("i([{}])<Esc>")
		t.expect(vim.api.nvim_get_current_line()).toBe("([{}])")
	end)
	t.it("backspaces paired text and keeps undo/redo atomic around pair insertion", function()
		feed("ia(<BS>[<Esc>")
		t.expect(vim.api.nvim_get_current_line()).toBe("a[]")
		feed("u")
		t.expect(vim.api.nvim_get_current_line()).toBe("a")
		vim.cmd("redo")
		t.expect(vim.api.nvim_get_current_line()).toBe("a[]")
	end)
	t.it("expands Enter using Blink's real fallback and leaves cursor on the middle line", function()
		feed("i{<CR>x<Esc>")
		t.expect(vim.api.nvim_buf_get_lines(0, 0, -1, false)).toEqual({ "{", "x", "}" })
		t.expect(vim.api.nvim_win_get_cursor(0)[1]).toBe(2)
	end)
	t.it("handles fences, triple quotes and disabled filetypes through actual typing", function()
		vim.bo.filetype = "markdown"
		feed("i```<Esc>")
		t.expect(vim.api.nvim_get_current_line()).toBe("``````")
		vim.api.nvim_buf_set_lines(0, 0, -1, false, { "" })
		vim.bo.filetype = "python"
		feed('i"""<Esc>')
		t.expect(vim.api.nvim_get_current_line()).toBe('""""""')
		vim.api.nvim_buf_set_lines(0, 0, -1, false, { "" })
		vim.bo.filetype = "vim"
		feed("i(<Esc>")
		t.expect(vim.api.nvim_get_current_line()).toBe("(")
	end)
	t.it("keeps replace mode and recorded macros literal", function()
		vim.api.nvim_buf_set_lines(0, 0, -1, false, { "xx" })
		feed("R(<Esc>")
		t.expect(vim.api.nvim_get_current_line()).toBe("(x")
		vim.api.nvim_buf_set_lines(0, 0, -1, false, { "" })
		local saved = vim.fn.getreginfo("q")
		feed("qqi(<Esc>q")
		t.expect(vim.api.nvim_get_current_line()).toBe("(")
		vim.api.nvim_buf_set_lines(0, 0, -1, false, { "" })
		feed("@q")
		t.expect(vim.api.nvim_get_current_line()).toBe("(")
		vim.fn.setreg("q", saved)
	end)
	t.it("wraps an existing quoted argument and respects indentation on Enter", function()
		for _, argument in ipairs({ '"é"', [=["escaped\"quote"]=] }) do
			vim.api.nvim_buf_set_lines(0, 0, -1, false, { argument })
			vim.api.nvim_win_set_cursor(0, { 1, 0 })
			feed("i(<Esc>")
			t.expect(vim.api.nvim_get_current_line()).toBe("(" .. argument .. ")")
		end
		vim.api.nvim_buf_set_lines(0, 0, -1, false, { "  " })
		feed("A{<CR>x<Esc>")
		t.expect(vim.api.nvim_buf_get_lines(0, 0, -1, false)).toEqual({ "  {", "  x", "  }" })
	end)

	t.it("accepts a real Blink snippet with Enter without retyping its brackets", function()
		local channel = vim.fn.jobstart({ "nvim", "--embed", "--headless", "-u", "NONE" }, { rpc = true })
		local function call(method, ...)
			local ok, value = pcall(vim.rpcrequest, channel, method, ...)
			if not ok then
				error(method .. ": " .. vim.inspect(value), 2)
			end
			return value
		end
		local function lua(code)
			return call("nvim_exec_lua", code, {})
		end
		local ok, err = xpcall(function()
			call("nvim_ui_attach", 100, 35, { rgb = true })
			lua("vim.o.loadplugins = true; dofile(" .. string.format("%q", vim.fn.stdpath("config") .. "/init.lua") .. ")")
			lua([[vim.cmd.enew(); vim.bo.filetype='lua']])
			call("nvim_input", "i(")
			t.expect(vim.wait(3000, function()
				return lua([[return vim.api.nvim_get_current_line() == '()']])
			end, 10)).toBe(true)
			t.expect(lua([[return require('blink.cmp.config').completion.menu.auto_show() ]])).toBe(false)
			lua([[require('blink.cmp').show({providers={'snippets'}})]])
			t.expect(vim.wait(3000, function()
				return lua([[return require('blink.cmp').is_menu_visible()]])
			end, 10)).toBe(true)
			call("nvim_input", "<Esc>")
			lua([[require('blink.cmp').hide(); vim.cmd.enew(); vim.bo.filetype='lua']])
			call("nvim_input", "ifori")
			t.expect(vim.wait(3000, function()
				return lua([[return vim.api.nvim_get_current_line() == 'fori']])
			end, 10)).toBe(true)
			lua([[require('blink.cmp').show({providers={'snippets'}})]])
			t.expect(vim.wait(3000, function()
				return lua([[return require('blink.cmp').is_menu_visible()]])
			end, 10)).toBe(true)
			lua([[
			local list = require('blink.cmp.completion.list')
			for i,item in ipairs(list.items) do
				if item.label == 'fori' then list.select(i); return end
			end
			error('Missing fori completion')
			]])
			call("nvim_input", "<CR>")
			t.expect(vim.wait(3000, function()
				return lua([[return vim.snippet.active()]])
			end, 10)).toBe(true)
			local result = lua([[return table.concat(vim.api.nvim_buf_get_lines(0,0,-1,false),'\n')]])
			t.expect(result).toContain("ipairs(")
			t.expect(result:find("ipairs((", 1, true)).toBe(nil)
			lua([[vim.snippet.stop()]])
		end, debug.traceback)
		vim.fn.jobstop(channel)
		assert(ok, err)
	end)
end)
