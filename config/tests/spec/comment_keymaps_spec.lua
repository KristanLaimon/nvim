local t = require("fox.lib.foxnvim.test")
require("keymaps.editor")

t.describe("Comment shortcuts", function()
	local buf, previous
	t.beforeEach(function()
		previous = vim.api.nvim_get_current_buf()
		buf = vim.api.nvim_create_buf(false, true)
		vim.api.nvim_set_current_buf(buf)
		vim.bo[buf].commentstring = "-- %s"
		vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "SELECT 1;", "SELECT 2;", "SELECT 3;" })
	end)
	t.afterEach(function()
		vim.api.nvim_feedkeys(vim.keycode("<Esc>"), "nx", false)
		vim.api.nvim_set_current_buf(previous)
		vim.api.nvim_buf_delete(buf, { force = true })
	end)
	local function press(keys)
		vim.api.nvim_feedkeys(vim.keycode(keys), "xt", false)
	end
	local function lines()
		return vim.api.nvim_buf_get_lines(buf, 0, -1, false)
	end

	t.it("toggles the current line twice with Ctrl+apostrophe", function()
		press("<C-'>")
		t.expect(lines()[1]).toBe("-- SELECT 1;")
		press("<C-'>")
		t.expect(lines()[1]).toBe("SELECT 1;")
	end)

	t.it("toggles a line and selection with the international acute-accent key", function()
		press("<C-´>")
		t.expect(lines()[1]).toBe("-- SELECT 1;")
		press("<C-´>")
		t.expect(lines()[1]).toBe("SELECT 1;")
		press("Vj<C-´>")
		t.expect(lines()[1]).toBe("-- SELECT 1;")
		t.expect(lines()[2]).toBe("-- SELECT 2;")
		t.expect(lines()[3]).toBe("SELECT 3;")
		press("ggVj<C-´>")
		t.expect(lines()[1]).toBe("SELECT 1;")
		t.expect(lines()[2]).toBe("SELECT 2;")
	end)

	t.it("toggles the current line even when gcc has a buffer-local mapping", function()
		vim.keymap.set("n", "gcc", "<Nop>", { buffer = buf })
		press("j<C-'>")
		t.expect(lines()).toEqual({ "SELECT 1;", "-- SELECT 2;", "SELECT 3;" })
		press("<C-'>")
		t.expect(lines()).toEqual({ "SELECT 1;", "SELECT 2;", "SELECT 3;" })
	end)

	t.it("toggles every selected line and leaves other lines alone", function()
		press("Vj<C-'>")
		t.expect(lines()[1]).toBe("-- SELECT 1;")
		t.expect(lines()[2]).toBe("-- SELECT 2;")
		t.expect(lines()[3]).toBe("SELECT 3;")
		press("ggVj<C-'>")
		t.expect(lines()[1]).toBe("SELECT 1;")
		t.expect(lines()[2]).toBe("SELECT 2;")
	end)

	t.it("accepts terminal CSI-u and modifyOtherKeys encodings", function()
		for _, key in ipairs({ "\27[39;5u", "\27[27;5;39~" }) do
			press(key)
			t.expect(lines()[1]).toBe("-- SELECT 1;")
			press(key)
			t.expect(lines()[1]).toBe("SELECT 1;")
			press("Vj" .. key)
			t.expect(lines()[1]).toBe("-- SELECT 1;")
			t.expect(lines()[2]).toBe("-- SELECT 2;")
			press("ggVj" .. key)
			t.expect(lines()[1]).toBe("SELECT 1;")
			t.expect(lines()[2]).toBe("SELECT 2;")
		end
	end)

	t.it("toggles a characterwise selection made upwards", function()
		press("jvk<C-'>")
		t.expect(lines()[1]).toBe("-- SELECT 1;")
		t.expect(lines()[2]).toBe("-- SELECT 2;")
		t.expect(lines()[3]).toBe("SELECT 3;")
		press("ggvj<C-'>")
		t.expect(lines()[1]).toBe("SELECT 1;")
		t.expect(lines()[2]).toBe("SELECT 2;")
	end)
end)
