local t = require("fox.lib.foxnvim.test")
local m = require("fox.ui.color_highlights")
t.describe("Color previews", function()
	t.it("parses valid short/alpha hex, rgb percentages and hsl", function()
		t.expect(m.color("#f008")).toBe("#ff0000")
		t.expect(m.color("#abcdef88")).toBe("#abcdef")
		t.expect(m.color("#12345")).toBe(nil)
		t.expect(m.color("rgb(100%, 0%, 0%)")).toBe("#ff0000")
		t.expect(m.color("hsl(120 100% 50%)")).toBe("#00ff00")
	end)
	t.it("renders byte-correct extmarks and removes stale colors after edits", function()
		vim.cmd("enew")
		local buf = vim.api.nvim_get_current_buf()
		vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "é #f00 rgb(0, 255, 0) rebeccapurple" })
		m.setup({})
		m.refresh(buf)
		local marks = vim.api.nvim_buf_get_extmarks(buf, m.ns, 0, -1, { details = true })
		t.expect(#marks).toBe(3)
		t.expect(marks[1][3]).toBe(3)
		vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "no colors here" })
		m.refresh(buf)
		t.expect(#vim.api.nvim_buf_get_extmarks(buf, m.ns, 0, -1, {})).toBe(0)
		vim.api.nvim_buf_delete(buf, { force = true })
	end)
	t.it("resolves CSS variables and optional Tailwind, and clears disabled previews", function()
		m.setup({ enable_tailwind = true })
		local spans = m.spans("var(--accent) bg-red-500", { ["--accent"] = "#123456" })
		t.expect(#spans).toBe(2)
		t.expect(spans[1][3]).toBe("#123456")
		m.toggle(false)
		m.setup({})
	end)
end)
