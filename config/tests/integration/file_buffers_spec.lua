local t = require("fox.lib.foxnvim.test")
require("lazy").load({ plugins = { "neo-tree.nvim" } })
t.describe("Neo-tree native buffer operations", function()
	t.it("moves a real file while retaining its dirty buffer and undo", function()
		local dir = vim.fn.tempname()
		vim.fn.mkdir(dir, "p")
		local old, new = dir .. "/old.lua", dir .. "/new.lua"
		vim.fn.writefile({ "original" }, old)
		vim.cmd.edit(old)
		local b = vim.api.nvim_get_current_buf()
		vim.api.nvim_buf_set_lines(b, 0, -1, false, { "edited" })
		local result = require("neo-tree.events").fire_event("before_file_rename", { source = old, destination = new })
		t.expect(result.handled).toBe(true)
		t.expect(vim.fn.filereadable(new)).toBe(1)
		t.expect(vim.api.nvim_buf_get_name(b)).toBe(new)
		t.expect(vim.bo[b].modified).toBe(true)
		t.expect(vim.fn.readfile(new)[1]).toBe("original")
		-- On delete, the same buffer/undo survives Neo-tree's force-close lookup.
		require("neo-tree.events").fire_event("before_file_delete", new)
		t.expect(vim.api.nvim_buf_get_name(b):match("^fox%-recovered://") ~= nil).toBe(true)
		t.expect(vim.api.nvim_buf_get_lines(b, 0, -1, false)[1]).toBe("edited")
		vim.api.nvim_buf_delete(b, { force = true })
		vim.fn.delete(dir, "rf")
	end)
end)
