local t = require("fox.lib.foxnvim.test")
require("lazy").load({ plugins = { "fox_buffer_cleaner" } })
local cleaner = _G.BufferCleaner

t.describe("buffer cleaner event batching", function()
	t.it("coalesces enter events and allows another cleanup after completion", function()
		cleaner.setup()

		-- Drain startup cleanup before observing a new batch of enter events.
		vim.wait(20)
		local calls = 0
		local clean = t.spyOn(cleaner, "clean_buffers")
		clean.mockImplementation(function()
			calls = calls + 1
		end)
		local ok, err = xpcall(function()
			for _ = 1, 3 do
				vim.api.nvim_exec_autocmds({ "BufEnter", "BufWinEnter" }, { group = "FOXCleanNoNameBuffers" })
			end
			t.expect(calls).toBe(0)
			t.expect(vim.wait(1000, function()
				return calls == 1
			end)).toBe(true)
			vim.api.nvim_exec_autocmds("BufEnter", { group = "FOXCleanNoNameBuffers" })
			t.expect(vim.wait(1000, function()
				return calls == 2
			end)).toBe(true)
		end, debug.traceback)
		clean.mockRestore()
		assert(ok, err)
	end)
end)

t.describe("Language Configure floating editor", function()
	t.it("closes defaults and native config without replacing the float with another buffer", function()
		local root, cwd = vim.fn.tempname(), vim.fn.getcwd()
		vim.fn.mkdir(root, "p")
		vim.fn.writefile({ "column_width = 100" }, root .. "/stylua.toml")
		vim.api.nvim_set_current_dir(root)
		vim.cmd.edit(vim.fn.fnameescape(root .. "/other.lua"))
		local other = vim.api.nvim_get_current_buf()
		vim.cmd.edit(vim.fn.fnameescape(root .. "/current.lua"))
		local editor = vim.api.nvim_get_current_win()
		local source = vim.api.nvim_get_current_buf()
		local function press(key)
			vim.fn.maparg(key, "n", false, true).callback()
		end
		local ok, err = xpcall(function()
			vim.cmd.ConfigureCurrentLanguage()
			press("<CR>")
			local list = vim.api.nvim_get_current_win()
			press("e")
			press("2")
			press("<CR>")
			local defaults = vim.api.nvim_get_current_win()
			t.expect(vim.inspect(vim.api.nvim_win_get_config(defaults).title)).toContain("stylua defaults")
			_G.Smart_Close_Tab()
			t.expect(vim.api.nvim_win_is_valid(defaults)).toBe(false)
			t.expect(vim.api.nvim_get_current_win()).toBe(list)

			press("e")
			press("<CR>")
			local config = vim.api.nvim_get_current_win()
			t.expect(vim.fn.expand("%:t")).toBe("stylua.toml")
			t.expect(vim.api.nvim_get_current_line()).toBe("column_width = 100")
			vim.cmd.FoxQ()
			t.expect(vim.api.nvim_win_is_valid(config)).toBe(false)
			t.expect(vim.api.nvim_get_current_win()).toBe(list)
			t.expect(vim.api.nvim_win_get_buf(editor)).toBe(source)
			t.expect(vim.api.nvim_buf_is_valid(other)).toBe(true)
		end, debug.traceback)
		vim.api.nvim_set_current_dir(cwd)
		vim.fn.delete(root .. "/stylua.toml")
		vim.fn.delete(root, "d")
		assert(ok, err)
	end)
end)
