local t = require("fox.lib.foxnvim.test")
local workspace = require("fox.reader.workspace")

t.describe("Reader workspace", function()
	t.it("restricts reads to included files inside the workspace and prefers loaded buffers", function()
		local root = assert(workspace.root(vim.fn.getcwd()))
		t.expect(workspace.resolve(root, "../outside.md")).toBe(nil)
		t.expect(workspace.resolve(root, "C:/outside.md")).toBe(nil)
		t.expect(workspace.included("README.md")).toBe(true)
		t.expect(workspace.included("notes.txt")).toBe(true)
		t.expect(workspace.included("notes.lua")).toBe(false)
		local buffer = vim.fn.bufadd(root .. "/README.md")
		vim.fn.bufload(buffer)
		local original = vim.api.nvim_buf_get_lines(buffer, 0, -1, false)
		vim.api.nvim_buf_set_lines(buffer, 0, -1, false, { "unsaved reader content" })
		t.expect(workspace.read(root, "README.md")).toBe("unsaved reader content")
		vim.api.nvim_buf_set_lines(buffer, 0, -1, false, original)
	end)
end)
